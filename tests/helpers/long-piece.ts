/**
 * An original test piece, generated: a long piece in A♭ major (4/4) with a melody over a half-note bass, phrases of four
 * bars, and C♭ in several bars (so the music borrows from A♭ minor). Deterministic in its arguments. Not music anyone
 * needs to like; it exists to give the course builders a long, many-stepped course. sections: the length of each
 * section in bars, used in turn (a number: all the same). The default mixes long sections (40 and 48 bars: ten and
 * twelve phrases, more than one row of the journey map holds at any width) with short ones.
 */
const SCALE = ['ab', 'bb', 'c', 'db', 'eb', 'f', 'g'];
const CHORDS: [string, number][] = [
  ['Ab', 0],
  ['Fm', 5],
  ['Db', 3],
  ['Eb', 4],
  ['Bbm', 1],
  ['Eb7', 4],
  ['Cm', 2],
  ['Abmaj7', 0],
];
/** A scale degree (0 = A♭) as a sounding pitch; base is the octave of the A♭ at degree 0. */
const pitch = (degree: number, base: number) => {
  const d = ((degree % 7) + 7) % 7,
    octave = base + Math.floor(degree / 7) + (d >= 2 ? 1 : 0);
  return `${SCALE[d]}${octave}`;
};

export const SECTIONS = [40, 12, 12, 8, 48];
export function longPiece(bars = 120, sizes: number | readonly number[] = SECTIONS, sections = true): string {
  let seed = 7;
  const next = () => (seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648;
  const names = ['Opening', 'Theme', 'Answer', 'Bridge', 'Theme2', 'Answer2', 'Interlude', 'Theme3', 'Coda', 'Close'];
  const lines = [
    '% An original test piece, generated for the tests. Not from any score.',
    'title: Long Walk Test',
    'composer: Test generator',
    'source: generated by tests/helpers/long-piece.ts',
    'licence: CC0',
    'redistributable: yes',
    'verified: checks',
    'pitch-mode: sounding',
    'key: 4b',
    'mode: major',
    'time: 4/4',
    'tempo: q=84 Steady',
    'voices: mel@1:R bass@2:L',
  ];
  const lengths = typeof sizes === 'number' ? [sizes] : sizes;
  if (sections)
    for (let s = 0, from = 1; from <= bars; s++) {
      const to = Math.min(bars, from + lengths[s % lengths.length] - 1);
      lines.push(`section: ${names[s % names.length]}${s >= names.length ? s : ''} ${from}-${to} "Part ${s + 1}."`);
      from = to + 1;
    }
  for (let b = 1; b <= bars; b++) {
    const [symbol, root] = CHORDS[(b * 3 + Math.floor(b / 5)) % CHORDS.length];
    lines.push(`== ${b}`, `harmony: ${symbol}`);
    const close = b % 4 === 0;
    if (close) lines.push(`mel: ${pitch(root + 7, 3)}:1`);
    else {
      const notes: string[] = [];
      for (let q = 0; q < 4; q++) {
        const step = [0, 2, 4, 1, 3, 5][Math.floor(next() * 6)];
        notes.push(q === 2 && b % 9 === 2 ? 'cb5:4' : `${pitch(root + step + 7, 3)}:4`);
      }
      lines.push(`mel: ${notes.join(' ')}`);
    }
    lines.push(`bass: ${pitch(root, 2)}:2 ${pitch(root + 4, 2)}:2`);
  }
  return lines.join('\n');
}
