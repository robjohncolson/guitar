/**
 * Golden output of piano listening: pianoOnsets and gradePiano (and verifyEvent for the recorded melody take) on the
 * real recordings used by piece-listen-recorded.test.ts plus three short synthetic takes. Every number must match
 * the stored file exactly; this guards speed work on listen.ts, which must not change a single verdict or value.
 * gradePiano keeps only verdicts, so each graded case also stores "probes": for every clear onset, attackRise asked
 * twice on one context (the second answer comes from the memo) and the full verifyEvent reading (every partial's
 * pre, post and floor level, and the rise). Those are the numbers the fft, floorAt, attackRise and memo paths produce.
 *
 * The golden file is NOT regenerated by a normal run. To regenerate it on purpose (only after an intended change to
 * the listening rules, never to make a speed-up pass), run:
 *   UPDATE_GOLDEN=1 npx vitest run tests/piece-listen-golden.test.ts
 * and review the diff of tests/fixtures/piano-listen-golden.json before committing it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { attackRise, eventContext, fft, pianoOnsets, verifyEvent, type PianoOnset } from '../src/piece/listen';
import { gradePiano, LENIENCY, setLeniency, type TakeAudio } from '../src/piece/grade';
import { fromBars, type Exercise } from '../src/piece/exercise';
import { compile } from '../src/piece/notation';
import gymnopedie from '../src/piece/packs/gymnopedie-1.piece.txt?raw';
import { addClicks, render, type Strike } from './helpers/piano-synth';

const goldenUrl = new URL('./fixtures/piano-listen-golden.json', import.meta.url);
const update = !!process.env.UPDATE_GOLDEN;

/** JSON keeps doubles exactly (shortest round-trip form); -0, NaN and infinities are tagged so they survive too. */
const exact = (value: unknown): unknown =>
  JSON.parse(
    JSON.stringify(value, (_, v) =>
      typeof v === 'number' && (!Number.isFinite(v) || Object.is(v, -0)) ? `#number:${Object.is(v, -0) ? '-0' : v}` : v,
    ),
  );

// Real Steinway notes, mixed exactly as in piece-listen-recorded.test.ts.
const meta = JSON.parse(readFileSync(new URL('./fixtures/piano-notes.json', import.meta.url), 'utf8'));
const wav = readFileSync(new URL('./fixtures/piano-notes.wav', import.meta.url));
const each = Math.round(meta.rate * meta.secondsPerNote);
const clips = new Map<number, Float32Array>();
const clip = (midi: number) => {
  const index = meta.midis.indexOf(midi);
  if (index < 0) throw new Error(`fixture lacks ${midi}`);
  if (!clips.has(midi))
    clips.set(
      midi,
      Float32Array.from({ length: each }, (_, i) => wav.readInt16LE(44 + 2 * (index * each + i)) / 32768),
    );
  return clips.get(midi)!;
};
interface Hit {
  midi: number;
  at: number;
  dur?: number;
}
function recorded(hits: Hit[], seconds: number, rate = meta.rate as number): Float32Array {
  const out = new Float32Array(Math.round(seconds * rate));
  let seed = 9;
  for (let i = 0; i < out.length; i++) {
    seed = (Math.imul(seed, 1664525) + 1013904223) | 0;
    out[i] = ((seed >>> 0) / 4294967296 - 0.5) * 0.0006;
  }
  for (const { midi, at, dur = 9 } of hits) {
    const source = clip(midi),
      start = Math.round(at * rate);
    for (let i = 0; i < Math.round(1.5 * rate) && start + i < out.length; i++) {
      const t = i / rate,
        position = t * meta.rate,
        floor = Math.floor(position),
        value = (source[floor] ?? 0) * (1 - (position - floor)) + (source[floor + 1] ?? 0) * (position - floor);
      out[start + i] += value * (t > dur ? Math.max(0, 1 - (t - dur) / 0.08) : 1);
    }
  }
  return out;
}
/**
 * For every onset gradePiano would consider (strength >= 0.12), a context bounded by its neighbours, asked in
 * gradePiano's order: attackRise (computed), attackRise again (remembered; it must be the same double), then
 * verifyEvent against the notes of the nearest expected event, which reads every partial and asks attackRise a third
 * time. The floor cache keeps the first value per quarter-bin key, so the reading depends on that order; it is kept.
 */
function probes(
  samples: Float32Array,
  rate: number,
  onsets: PianoOnset[],
  ex: Exercise,
  at: (beat: number) => number,
  clicks: boolean,
) {
  const strong = onsets.filter((o) => o.strength >= 0.12);
  return strong.map((o, j) => {
    const nearest = ex.events.reduce((a, b) => (Math.abs(at(b.beat) - o.t) < Math.abs(at(a.beat) - o.t) ? b : a)),
      expected = nearest.notes.map((n) => n.midi);
    const ctx = eventContext(samples, rate, o.t, strong[j - 1]?.t, strong[j + 1]?.t, 0, clicks),
      rise = attackRise(ctx),
      again = attackRise(ctx),
      verify = verifyEvent(ctx, expected);
    expect(Object.is(again, rise), `memo at ${o.t}`).toBe(true);
    expect(Object.is(verify.rise, rise), `rise inside verifyEvent at ${o.t}`).toBe(true);
    return { t: o.t, expected, rise, again, verify };
  });
}

const score = compile(gymnopedie).score!,
  intro = fromBars(score, [0, 1, 2, 3], ['L'], 'L:1-4', 'Intro');
const introHits = (change: (h: Hit) => Hit | undefined = (h) => h) =>
  intro.events
    .flatMap((e) =>
      e.notes.map((n) => change({ midi: n.midi, at: 0.6 + e.beat + (n.midi % 3) * 0.007, dur: Math.min(1.4, n.dur) })),
    )
    .filter(Boolean) as Hit[];
/** The recorded test's call: onsets over the whole take, offset 0, at 60 BPM. */
const gradeRecorded = (hits: Hit[], rate = meta.rate as number) => {
  const samples = recorded(hits, 0.6 + intro.beats + 1, rate),
    onsets = pianoOnsets(samples, rate, 0, samples.length / rate);
  return {
    onsets,
    grade: gradePiano(intro, 60, { samples, rate, playAt: 0.6, coverage: 1, clipped: 0, clicks: false }, onsets, 0),
    probes: probes(samples, rate, onsets, intro, (beat) => 0.6 + beat, false),
  };
};

/** Synthetic takes graded the way analysis.worker.ts does, with the capture margins audio.ts uses. */
const bpm = 66,
  period = 60 / bpm,
  playAt = 0.5;
function synthetic(ex: Exercise, rate: number, change: (s: Strike) => Strike | undefined = (s) => s, clicks = false) {
  const strikes = ex.events
    .flatMap((e) =>
      e.notes.map((n) =>
        change({
          midi: n.midi,
          at: playAt + e.beat * period + (((n.midi * 7919) % 13) - 6) * 0.003,
          dur: Math.min(1.5, n.dur * period),
          amp: 0.12,
        }),
      ),
    )
    .filter(Boolean) as Strike[];
  const samples = render(rate, playAt + ex.beats * period + 0.75, strikes, 0.0006, 3);
  if (clicks)
    addClicks(
      samples,
      rate,
      Array.from({ length: Math.ceil(ex.beats) }, (_, b) => playAt + b * period),
      0.03,
    );
  const take: TakeAudio = { samples, rate, playAt, coverage: 1, clipped: 0, interrupted: false, clicks };
  const onsets = pianoOnsets(samples, rate, Math.max(0, playAt - 0.3), playAt + ex.beats * period + 0.4, clicks);
  return {
    onsets,
    grade: gradePiano(ex, bpm, take, onsets, 0, true),
    probes: probes(samples, rate, onsets, ex, (beat) => playAt + beat * period, clicks),
  };
}

function compute(): Record<string, unknown> {
  setLeniency(LENIENCY.relaxed);
  const out: Record<string, unknown> = {};
  out['recorded intro 24 kHz'] = gradeRecorded(introHits(), 24000);
  out['recorded intro 48 kHz'] = gradeRecorded(introHits(), 48000);
  out['recorded intro, wrong chord tone'] = gradeRecorded(
    introHits((h) => (h.midi === 61 && h.at > 9 ? { ...h, midi: 60 } : h)),
  );
  out['recorded intro, missing chord tone'] = gradeRecorded(
    introHits((h) => (h.midi === 62 && h.at < 3 ? undefined : h)),
  );
  const melody = recorded(
    [
      { midi: 78, at: 0.5 },
      { midi: 81, at: 1.5 },
    ],
    3,
  );
  out['recorded melody 78 then 81'] = {
    onsets: pianoOnsets(melody, meta.rate, 0, melody.length / meta.rate),
    first: verifyEvent(eventContext(melody, meta.rate, 0.5, undefined, 1.45), [78]),
    swapped: verifyEvent(eventContext(melody, meta.rate, 1.5, 0.5, undefined), [78]),
  };
  // Theme, bars 5 and 6, right hand alone, with metronome clicks leaking into the microphone.
  out['synthetic single-hand step with clicks, 48 kHz'] = synthetic(
    fromBars(score, [4, 5], ['R'], 'R:5-6', 'Step'),
    48000,
    (s) => s,
    true,
  );
  const passage = fromBars(score, [4, 5, 6], ['L', 'R'], 'LR:5-7', 'Passage');
  out['synthetic both hands with chords, 24 kHz'] = synthetic(passage, 24000);
  // One melody note a semitone sharp (a wrong key) and one left-hand chord tone left out.
  const melodyNote = passage.events
    .flatMap((e) => e.notes.map((n) => ({ beat: e.beat, n })))
    .find((x) => x.beat >= 3 && x.n.hand === 'R')!;
  const chord = passage.events.find((e) => e.beat >= 6 && e.notes.length >= 3)!;
  const dropMidi = chord.notes[1].midi,
    dropAt = playAt + chord.beat * period;
  out['synthetic wrong note and missing note, 24 kHz'] = {
    changed: {
      wrong: { beat: melodyNote.beat, midi: melodyNote.n.midi },
      missing: { beat: chord.beat, midi: dropMidi },
    },
    ...synthetic(passage, 24000, (s) => {
      if (s.midi === dropMidi && Math.abs(s.at - dropAt) < 0.05) return undefined;
      if (s.midi === melodyNote.n.midi && Math.abs(s.at - (playAt + melodyNote.beat * period)) < 0.05)
        return { ...s, midi: s.midi + 1 };
      return s;
    }),
  };
  return out;
}

it('piano listening reproduces the golden onsets and grades exactly', { timeout: 60000 }, () => {
  const actual = exact(compute()) as Record<string, unknown>;
  if (update) writeFileSync(goldenUrl, JSON.stringify(actual, null, 1) + '\n');
  const golden = JSON.parse(readFileSync(goldenUrl, 'utf8'));
  expect(Object.keys(actual)).toEqual(Object.keys(golden));
  for (const key of Object.keys(golden)) expect(actual[key], key).toEqual(golden[key]);
});

/** The fft listen.ts used before its speed-up, kept verbatim as the reference. */
const referenceTwiddles = new Map<number, { cos: Float64Array; sin: Float64Array }>();
function referenceFft(re: Float64Array, im: Float64Array): void {
  const n = re.length;
  let table = referenceTwiddles.get(n);
  if (!table) {
    table = { cos: new Float64Array(n / 2), sin: new Float64Array(n / 2) };
    for (let i = 0; i < n / 2; i++) {
      table.cos[i] = Math.cos((-2 * Math.PI * i) / n);
      table.sin[i] = Math.sin((-2 * Math.PI * i) / n);
    }
    referenceTwiddles.set(n, table);
  }
  for (let i = 1, j = 0; i < n; i++) {
    let bit = n >> 1;
    for (; j & bit; bit >>= 1) j ^= bit;
    j ^= bit;
    if (i < j) {
      let t = re[i];
      re[i] = re[j];
      re[j] = t;
      t = im[i];
      im[i] = im[j];
      im[j] = t;
    }
  }
  for (let len = 2; len <= n; len <<= 1) {
    const half = len >> 1,
      step = n / len;
    for (let i = 0; i < n; i += len)
      for (let j = 0; j < half; j++) {
        const c = table.cos[j * step],
          s = table.sin[j * step],
          a = i + j,
          b = a + half;
        const br = re[b] * c - im[b] * s,
          bi = re[b] * s + im[b] * c;
        re[b] = re[a] - br;
        im[b] = im[a] - bi;
        re[a] += br;
        im[a] += bi;
      }
  }
}

it('fft is bit-identical to the reference fft for sizes 256 to 32768', () => {
  let seed = 12345;
  const random = () => {
    seed = (Math.imul(seed, 1664525) + 1013904223) | 0;
    return (seed >>> 0) / 4294967296 - 0.5;
  };
  /** Compares the raw 64-bit patterns, so even -0 against +0 would count as a difference. */
  const bits = (x: Float64Array) => Array.from(new BigUint64Array(x.buffer, x.byteOffset, x.length));
  for (let n = 256; n <= 32768; n *= 2) {
    const inputs: [string, Float64Array, Float64Array][] = [
      ['random', Float64Array.from({ length: n }, random), Float64Array.from({ length: n }, random)],
      [
        'sines',
        Float64Array.from(
          { length: n },
          (_, i) => 0.7 * Math.sin(0.0731 * i) + 0.2 * Math.sin((2 * Math.PI * 37 * i) / n),
        ),
        new Float64Array(n),
      ],
      ['random real', Float64Array.from({ length: n }, random), new Float64Array(n)],
    ];
    for (const [name, re, im] of inputs) {
      const re1 = re.slice(),
        im1 = im.slice(),
        re2 = re.slice(),
        im2 = im.slice();
      fft(re1, im1);
      referenceFft(re2, im2);
      expect(bits(re1), `${name} ${n} re`).toEqual(bits(re2));
      expect(bits(im1), `${name} ${n} im`).toEqual(bits(im2));
    }
  }
});
